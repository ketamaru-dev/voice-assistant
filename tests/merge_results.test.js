// Запуск:  jsc tests/merge_results.test.js   (macOS)   или   node tests/merge_results.test.js
// Тестируется реальный код mergeResults из static/index.html (он вырезается из файла по маркерам).

const isNode = typeof require === 'function' && typeof process !== 'undefined';
const html = isNode
  ? require('fs').readFileSync(require('path').join(__dirname, '../static/index.html'), 'utf8')
  : read('static/index.html');

const start = html.indexOf('const normKey');
const end = html.indexOf('let lastSent');
if (start < 0 || end < 0) throw new Error('Не найден код mergeResults в static/index.html');
const mergeResults = new Function(html.slice(start, end) + '; return mergeResults;')();

const mk = arr => arr.map(t => [{ transcript: t }]);
const log = isNode ? console.log : print;

let passed = 0, failed = 0;
function test(name, results, lang, expected) {
  const actual = mergeResults(mk(results), lang);
  if (actual === expected) { passed++; log('  ok   ' + name); }
  else { failed++; log('  FAIL ' + name + '\n         ожидалось: ' + JSON.stringify(expected) + '\n         получено:  ' + JSON.stringify(actual)); }
}

log('mergeResults');

// Накопительные результаты Android Chrome
test('накопительные куски -> последний', ['смотрю', 'смотрю как', 'смотрю как это', 'смотрю как это всё работает'], 'ru', 'смотрю как это всё работает');
test('накопительные куски без пробелов-дублей (баг со скриншота)', ['смотрю', 'смотрю как', 'смотрю как это', 'смотрю как это всё', 'смотрю как это всё работает', 'смотрю как это всё работает здесь'], 'ru', 'смотрю как это всё работает здесь');

// Финал с другим регистром/пунктуацией
test('финал с заглавной и точкой заменяет промежуточный', ['смотрю как это всё работает', 'Смотрю, как это всё работает.'], 'ru', 'Смотрю, как это всё работает.');
test('короткий повтор после длинного пропускается', ['Смотрю, как это всё работает.', 'смотрю как это'], 'ru', 'Смотрю, как это всё работает.');
test('промежуточный, финал и повтор промежуточного', ['смотрю как это', 'Смотрю, как это всё работает.', 'смотрю как это всё работает'], 'ru', 'смотрю как это всё работает');
test('английский: разный регистр и знаки', ['Hello how are you', 'Hello, how are you?', 'hello how are you'], 'en', 'hello how are you');

// Обычное поведение десктопа: независимые куски
test('независимые куски склеиваются через пробел', ['привет как', 'дела у тебя'], 'ru', 'привет как дела у тебя');
test('куски с ведущими пробелами', ['привет', ' как дела'], 'ru', 'привет как дела');
test('одиночный результат без изменений', ['Привет, мир'], 'ru', 'Привет, мир');

// Пересечения по словам
test('перекрытие хвоста и начала по словам', ['привет как дела', 'как дела у тебя'], 'ru', 'привет как дела у тебя');
test('полное вхождение пропускается', ['привет как дела у тебя', 'дела у тебя'], 'ru', 'привет как дела у тебя');

// Повторы целиком
test('фраза, повторённая целиком, сворачивается', ['привет привет привет'], 'ru', 'привет');
test('составная фраза, повторённая целиком', ['как дела как дела как дела'], 'ru', 'как дела');
test('одинаковые результаты подряд -> одна фраза', ['привет как дела', 'привет как дела', 'привет как дела'], 'ru', 'привет как дела');
test('частичное повторение слов НЕ сворачивается', ['очень очень хорошо'], 'ru', 'очень очень хорошо');

// Граничные случаи
test('пустой список', [], 'ru', '');
test('только пустые и пробельные результаты', ['', '   ', '.'], 'ru', '');
test('пустой результат между кусками игнорируется', ['привет', '', 'как дела'], 'ru', 'привет как дела');

// Языки без пробелов
test('китайский: накопительные куски', ['你好', '你好吗'], 'zh', '你好吗');
test('японский: независимые куски без пробела', ['こんにちは', 'ありがとう'], 'ja', 'こんにちはありがとう');

// Сербский
test('сербский: кириллица накопительно', ['здраво', 'Здраво, како си?'], 'sr', 'Здраво, како си?');
test('сербский: латиница с диакритикой', ['dobro jutro', 'Dobro jutro, gde je apoteka?'], 'sr', 'Dobro jutro, gde je apoteka?');

log('\n' + passed + ' passed, ' + failed + ' failed');
if (failed) { if (isNode) process.exit(1); else throw new Error(failed + ' tests failed'); }
